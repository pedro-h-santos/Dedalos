void Map_init(Map *m){
    m->lin = MAP_LINHAS;
    m->col = MAP_COLUNAS;
    memcpy(m->grid, mapa_padrao, sizeof(mapa_padrao));
}
int Map_getgrid(Map *m, int x, int y){
    if(x <0 || x >= m->col || y < 0 || y >= m->lin)
    return 1;
    return m->grid[y][x];
}
bool Map_iswalkable(Map *m, float x, float y){
    return Map_getgrid(m, (int)x, (int)y) == 0;
}